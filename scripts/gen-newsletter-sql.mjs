// Writes migrations/023_newsletter.sql from lib/newsletter/content.js (the one source of the
// newsletter + "Personalize your profile" email copy). Run: node scripts/gen-newsletter-sql.mjs
import fs from 'node:fs';
import { NEWSLETTER_TEMPLATES, PROFILE_TEMPLATES, ISSUES, issueKey } from '../lib/newsletter/content.js';

const q = (s) => (s == null ? 'null' : `$cl$${String(s)}$cl$`);
const cols = (t) => `${q(t.key)}, ${q(t.name)}, ${q(t.subject)}, ${q(t.heading)}, ${q(t.body)}, ${q(t.button_label)}, ${q(t.button_url)}`;

const out = [];
out.push(`-- Casa-Libre — weekly newsletter templates + automation row, and the rewritten
-- "Personalize your profile" emails (Roland, 2026-11-21: one or two lines + the mock listing image).
-- GENERATED by scripts/gen-newsletter-sql.mjs from lib/newsletter/content.js — edit there, re-run.
-- Apply to EACH country DB (PY, BO, UY, VE, SV) in the AiroBase SQL editor. Idempotent: safe to
-- run twice. No begin/commit (the editor rejects them). No new table or column.
--   1. the ${NEWSLETTER_TEMPLATES.length} newsletter templates (key newsletter-…): inserted once; an existing row
--      (maybe edited in the admin) is left as it is
--   2. the two profile templates (key profile-personalize, profile-personalize-reminder):
--      REPLACED with the new copy (inserted when missing)
--   3. the 'newsletter' automation row, switched OFF, Tuesday 10:00, rotation = all newsletter
--      templates in order with their suggested audience (settings in free_tiers[0])
`);
out.push('-- 1. Newsletter templates');
for (const t of NEWSLETTER_TEMPLATES) {
  out.push(`insert into public.email_templates (key, name, subject, heading, body, button_label, button_url, is_active)
values (${cols(t)}, true)
on conflict (key) do nothing;`);
}
out.push('\n-- 2. "Personalize your profile" — the new copy');
for (const t of PROFILE_TEMPLATES) {
  out.push(`insert into public.email_templates (key, name, subject, heading, body, button_label, button_url, is_active)
values (${cols(t)}, true)
on conflict (key) do update set name = excluded.name, subject = excluded.subject, heading = excluded.heading,
  body = excluded.body, button_label = excluded.button_label, button_url = excluded.button_url, updated_at = now();`);
}
const values = ISSUES.map((i, n) => `('${issueKey(i.slug)}', '${i.audience}', ${n + 1})`).join(',\n    ');
out.push(`
-- 3. The newsletter automation (OFF). The admin's Automations page edits day / hour / rotation.
insert into public.automations (id, enabled, wait_days, free_tiers, updated_at)
select 'weekly_newsletter', false, 0, jsonb_build_array(jsonb_build_object(
  'day', 2, 'hour', 10, 'next', 0,
  'rotation', coalesce((
    select jsonb_agg(jsonb_build_object('template_id', t.id, 'audience', v.aud) order by v.ord)
    from (values
    ${values}
    ) as v(k, aud, ord)
    join public.email_templates t on t.key = v.k
  ), '[]'::jsonb))), now()
on conflict (id) do nothing;
`);
fs.writeFileSync(new URL('../migrations/023_newsletter.sql', import.meta.url), out.join('\n') + '\n');
console.log('wrote migrations/023_newsletter.sql');
